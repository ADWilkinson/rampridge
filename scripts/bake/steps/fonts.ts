/**
 * RuneScape fonts (RuneStar TrueType conversions, fetched from a pinned
 * release by fetch-fonts.ts) -> public/game/fonts with fonts.css and a licence
 * note. The fonts are pixel fonts: one font unit is one pixel, so they are
 * crisp at font-size = unitsPerEm (16px for the 11/12/Bold/Quill 8 faces).
 */
import fs from "node:fs";
import path from "node:path";

import { ensureRuneStarFonts, RUNESTAR_FONTS, RUNESTAR_RELEASE } from "../fetch-fonts";
import { FONTS_DIR, rel, writeIfChanged } from "../lib/paths";

/** CSS family, file, pixel-perfect size (font units per em) and the client font it reproduces. */
export const FONTS = [
  { family: "RS Plain 11", file: "RuneScape-Plain-11.ttf", px: 16, client: "p11_full" },
  { family: "RS Plain 12", file: "RuneScape-Plain-12.ttf", px: 16, client: "p12_full" },
  { family: "RS Bold 12", file: "RuneScape-Bold-12.ttf", px: 16, client: "b12_full" },
  { family: "RS Quill 8", file: "RuneScape-Quill-8.ttf", px: 16, client: "q8_full" },
  { family: "RS Quill", file: "RuneScape-Quill.ttf", px: 32, client: "quill_oblique_large" },
  { family: "RS Quill Caps", file: "RuneScape-Quill-Caps.ttf", px: 64, client: "quill_caps_large" },
  { family: "RS Fairy", file: "RuneScape-Fairy.ttf", px: 32, client: "lunar_alphabet" },
  { family: "RS Fairy Large", file: "RuneScape-Fairy-Large.ttf", px: 64, client: "lunar_alphabet_lrg" },
  { family: "RS Barbarian Assault", file: "RuneScape-Barbarian-Assault.ttf", px: 32, client: "barbassault_font" },
  { family: "RS Surok", file: "RuneScape-Surok.ttf", px: 16, client: "surok_font" },
] as const;

export async function bakeFonts(): Promise<void> {
  const source = await ensureRuneStarFonts();
  const written = new Set<string>();
  for (const f of FONTS) {
    if (!RUNESTAR_FONTS[f.file]) throw new Error(`${f.file} is not one of the pinned RuneStar fonts (fetch-fonts.ts)`);
    writeIfChanged(path.join(FONTS_DIR, f.file), fs.readFileSync(path.join(source, f.file)));
    written.add(f.file);
  }

  const css = [
    "/*",
    " * RuneScape fonts for RampRidge. Generated by scripts/bake (steps/fonts.ts).",
    " * Pixel fonts: one font unit = one pixel. Render at the size noted per face (or an integer",
    " * multiple) with font-smooth off for the original look, e.g.",
    " *   font: 16px \"RS Plain 12\"; -webkit-font-smoothing: none; font-smooth: never;",
    " * Client equivalents: RS Plain 11 = p11_full (chat, small text), RS Plain 12 = p12_full",
    " * (interfaces, overhead chat), RS Bold 12 = b12_full (titles, menus), RS Quill 8 = q8_full",
    " * (headings, the login screen). Glyphs (c) Jagex Ltd; TrueType conversion by RuneStar (CC0).",
    " */",
    ...FONTS.map(
      (f) =>
        `/* ${f.client}: pixel-perfect at ${f.px}px */\n@font-face {\n  font-family: "${f.family}";\n  src: url("./${f.file}") format("truetype");\n  font-weight: normal;\n  font-style: normal;\n  font-display: block;\n}`,
    ),
    "",
  ].join("\n");
  writeIfChanged(path.join(FONTS_DIR, "fonts.css"), css);
  written.add("fonts.css");

  const licence = `# RuneScape fonts

The TrueType files in this directory are RuneStar's conversions of the fonts in the
Old School RuneScape client (https://github.com/RuneStar/fonts, release ${RUNESTAR_RELEASE}).

- Conversion: dedicated to the public domain by RuneStar (CC0 1.0).
- Glyph designs: (c) Jagex Ltd. RuneScape and Old School RuneScape are trademarks of Jagex Ltd.

Copied by scripts/bake (steps/fonts.ts) from the release, which scripts/bake/fetch-fonts.ts
downloads and checks against pinned SHA-256 hashes. Not committed to the repository.
`;
  writeIfChanged(path.join(FONTS_DIR, "LICENSE.md"), licence);
  written.add("LICENSE.md");

  for (const f of fs.readdirSync(FONTS_DIR)) if (!written.has(f)) fs.rmSync(path.join(FONTS_DIR, f));
  console.log(`  fonts: ${FONTS.length} faces + fonts.css -> ${rel(FONTS_DIR)}`);
}
